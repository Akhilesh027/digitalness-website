/* ============================================================
   WORKFLOW
============================================================ */

function buildProcess({

  name,
  category,
  outcome,
  features,
  deliverables

}) {

  const categoryInfo =
    categoryContent[category] ||
    categoryContent['Other Services'];


  const titles = [

    `Clarify the ${name} objective`,

    ...deliverables

  ];


  const descriptions = [

    `${categoryInfo.process} For ${name}, we define what success ` +
    `should look like in relation to ${outcome}.`,


    ...deliverables.map(
      (deliverable, index) => {

        const feature =
          features[
            index %
            features.length
          ];


        if (index === 0) {

          return (
            `${deliverable} turns the strategy into a practical working layer, ` +
            `with ${feature.toLowerCase()} connected to the business objective.`
          );

        }


        if (index === 1) {

          return (
            `${deliverable} is developed around ${feature.toLowerCase()} ` +
            `so execution remains aligned with the intended customer journey.`
          );

        }


        if (index === 2) {

          return (
            `${deliverable} creates a usable structure for ` +
            `${feature.toLowerCase()} before the next stage is expanded.`
          );

        }


        if (index === 3) {

          return (
            `${deliverable} helps validate how ${feature.toLowerCase()} ` +
            `should work before launch or scaling.`
          );

        }


        return (
          `${deliverable} closes the loop between execution and review, ` +
          `helping determine whether ${name.toLowerCase()} ` +
          `is moving toward ${outcome}.`
        );

      }
    )

  ];


  return {

    titles,

    descriptions

  };

}


