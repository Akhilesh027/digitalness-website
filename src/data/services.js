/* ============================================================
   HELPERS
============================================================ */

function capitalize(text = '') {

  if (!text) {
    return '';
  }

  return (
    text.charAt(0).toUpperCase() +
    text.slice(1)
  );

}


function lowerFirst(text = '') {

  if (!text) {
    return '';
  }

  return (
    text.charAt(0).toLowerCase() +
    text.slice(1)
  );

}


/* ============================================================
   CAPABILITY DESCRIPTIONS
============================================================ */

function buildCapabilityDescriptions({

  name,
  focus,
  outcome,
  audience,
  features,
  deliverables

}) {

  return features.map(
    (feature, index) => {

      const deliverable =
        deliverables[
          index %
          deliverables.length
        ];


      if (index === 0) {

        return (
          `${capitalize(feature)} creates the foundation for ${focus}. ` +
          `It gives the ${name.toLowerCase()} engagement a clear starting structure.`
        );

      }


      if (index === 1) {

        return (
          `${capitalize(feature)} is planned around ${audience}, ` +
          `keeping execution relevant to the people the service needs to influence.`
        );

      }


      if (index === 2) {

        return (
          `${capitalize(feature)} connects execution to ${outcome}, ` +
          `supported by ${lowerFirst(deliverable)} as a practical working output.`
        );

      }


      return (
        `${capitalize(feature)} helps evaluate how ${name.toLowerCase()} ` +
        `is working in practice and what should be improved next.`
      );

    }
  );

}


